'use strict';
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const assert = require('node:assert/strict');
const ROOT = path.resolve(__dirname, '..'), OUT = path.join(ROOT, '.shots/customer-selection');
fs.mkdirSync(OUT, { recursive: true });
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'dns-customer-selection-'));
for (const [key, folder] of Object.entries({ DNS_TEST_USER_DATA: 'profile', DNS_TEST_DATA_DIR: 'data', DNS_TEST_BACKUP_DIR: 'backup', DNS_TEST_IMAGE_DIR: 'images', DNS_TEST_SAVE_DIR: 'exports' })) process.env[key] = path.join(temp, folder);
app.setPath('userData', process.env.DNS_TEST_USER_DATA);
app.disableHardwareAcceleration();
const pause = ms => new Promise(resolve => setTimeout(resolve, ms)), errors = [];
const timeout = setTimeout(() => { console.error('CUSTOMER_SELECTION_TIMEOUT'); app.exit(1); }, 60000);
app.on('web-contents-created', (_event, contents) => contents.on('console-message', (_e, level, message) => { if (level >= 3) errors.push(message); }));
require(path.join(ROOT, 'main.js'));

app.whenReady().then(async () => {
  let win;
  for (let i = 0; i < 200; i++) { win = BrowserWindow.getAllWindows()[0]; if (win) break; await pause(30); }
  assert.ok(win);
  const js = code => win.webContents.executeJavaScript(code, true);
  const wait = async code => {
    for (let i = 0; i < 200; i++) { try { if (await js(code)) return; } catch (_) {} await pause(30); }
    throw new Error('Timeout: ' + code);
  };
  const nav = async hash => { await js('location.hash=' + JSON.stringify(hash)); await pause(150); };
  const open = async hash => {
    await nav(hash);
    await js('window.customerView=document.querySelector("#view-container .view");window.customerDraft=customerView.__draft;void 0');
  };
  const pick = async key => {
    await js(`customerView.querySelector('[data-act="pick-cust"]').click();document.querySelector('[data-pick-cust="'+customerFixture[${JSON.stringify(key)}].id+'"]').click();void 0`);
  };
  const visible = () => js('!!customerView.querySelector("[data-act=clear-cust]").getBoundingClientRect().width');
  const snapshot = () => js('JSON.stringify(JSON.parse(Store.exportJSON()).data)');
  await wait('!!window.DNSDesktop?.ready');
  win.setContentSize(1440, 1000);
  win.webContents.setBackgroundThrottling(false);
  await js(`Store.clearAll();DNSDesktop.setSceneEnabled(false);
    window.customerFixture={a:Store.upsertCustomer({name:'测试A',phone:'13800000001',address:'客户A地址'}),b:Store.upsertCustomer({name:'测试B'})};
    customerFixture.product=Store.upsertProduct({name:'怡宝饮用纯净水',spec:'555ml',unit:'瓶',price:2});
    Store.setLastPrice(customerFixture.a.id,customerFixture.product.id,8);void 0`);
  await open('#/order/new');
  assert.equal(await visible(), false);
  await pick('a');
  assert.equal(await visible(), true);
  assert.equal(await js('customerDraft.customer.id'), await js('customerFixture.a.id'));
  await js(`customerView.querySelector('[data-act="add-item"]').click();
    const dialog=document.querySelector('.item-dialog'),name=dialog.querySelector('[data-role="name"]');
    name.value=customerFixture.product.name;name.dispatchEvent(new Event('input',{bubbles:true}));
    dialog.querySelector('[data-pick-pid="'+customerFixture.product.id+'"]').click();
    dialog.querySelector('[data-role="qty"]').value='21';dialog.querySelector('[data-role="price"]').value='2';
    dialog.querySelector('[data-act="ok"]').click();
    window.customerItemsBefore=JSON.stringify(customerDraft.items);window.customerCard=customerView.querySelector('.oi-card');
    window.customerFieldsBefore=JSON.stringify({no:customerDraft.no,date:customerDraft.date,operator:customerDraft.operator,total:customerDraft.total});void 0`);
  const before = await snapshot();
  await pause(180);
  fs.writeFileSync(path.join(OUT, 'selected.png'), (await win.webContents.capturePage()).toPNG());
  await js('customerView.querySelector("[data-act=clear-cust]").click();void 0');
  assert.equal(await js('customerDraft.customer'), null);
  assert.equal(await visible(), false);
  assert.equal(await js('customerView.querySelector("[data-role=cname]").textContent'), '选择客户（可选）');
  assert.equal((await js('customerView.querySelector("[data-role=csub]").textContent')).trim(), '');
  assert.equal(await js('document.activeElement===customerView.querySelector("[data-act=pick-cust]")'), true);
  assert.equal(await js('!!document.querySelector("#modal-root .sheet")'), false);
  assert.equal(await js('JSON.stringify(customerDraft.items)'), await js('customerItemsBefore'));
  assert.equal(await js('JSON.stringify({no:customerDraft.no,date:customerDraft.date,operator:customerDraft.operator,total:customerDraft.total})'), await js('customerFieldsBefore'));
  assert.equal(await js('customerView.querySelector(".oi-card")===customerCard'), true);
  assert.equal(await snapshot(), before);
  await pause(180);
  fs.writeFileSync(path.join(OUT, 'cleared.png'), (await win.webContents.capturePage()).toPNG());
  console.log('PASS new order clears selected customer without opening picker, rewriting items or writing storage');

  await pick('b');
  assert.equal(await visible(), true);
  assert.equal(await js('customerView.querySelector("[data-role=cname]").textContent'), '测试B');
  await pick('a');
  assert.equal(await js('customerDraft.customer.id'), await js('customerFixture.a.id'));
  await js('customerView.querySelector("[data-act=clear-cust]").focus();void 0');
  assert.equal(await js('document.activeElement===customerView.querySelector("[data-act=clear-cust]")'), true);
  assert.equal(await js('document.activeElement.tagName'), 'BUTTON');
  await js('document.activeElement.click();void 0');
  await wait('customerDraft.customer===null');
  await js('customerView.querySelector("[data-act=save]").click();void 0');
  await wait('location.hash.startsWith("#/order/view?id=")');
  const saved = await js('Store.getOrder(DNSDesktop.state.selectedId)');
  assert.equal(saved.customer, null);
  assert.equal(saved.items[0].qty, 21);
  assert.equal(saved.items[0].price, 2);
  assert.equal(saved.total, 42);
  assert.equal(await js('Store.getLastPrice(customerFixture.a.id,customerFixture.product.id)'), 8);
  assert.equal(await js('Store.countAll().customers'), 2);
  const disk = JSON.parse(fs.readFileSync(path.join(process.env.DNS_TEST_DATA_DIR, 'sd_v1_orders.json')));
  assert.equal(disk.find(order => order.id === saved.id).customer, null);
  await nav('#/print?id=' + saved.id);
  assert.equal(await js('!!document.querySelector(".d-customer-name")'), false);
  assert.doesNotMatch(await js('document.querySelector(".d-meta").textContent'), /客户名称|客户电话|客户地址/);
  console.log('PASS reselect and replace; saving retains null customer on disk and leaves customer price history intact');

  const original = await js(`Store.addOrder({no:'CUSTOMER-EDIT',date:'2026-11-12',customer:customerFixture.a,items:[{pid:customerFixture.product.id,name:customerFixture.product.name,spec:'555ml',unit:'瓶',qty:3,price:2,amount:6,remark:''}],total:6})`);
  await open('#/order/edit?id=' + original.id);
  assert.equal(await visible(), true);
  await js('customerView.querySelector("[data-act=clear-cust]").click();void 0');
  assert.equal(await js('Store.getOrder(' + JSON.stringify(original.id) + ').customer.id'), original.customer.id);
  await js('customerView.querySelector("[data-act=save]").click();void 0');
  await wait('location.hash.startsWith("#/order/view?id=")');
  const updated = await js('Store.getOrder(' + JSON.stringify(original.id) + ')');
  assert.equal(updated.customer, null);
  assert.equal(updated.no, original.no);
  assert.deepEqual(updated.items, original.items);
  assert.equal(updated.total, original.total);
  await open('#/order/edit?id=' + original.id);
  assert.equal(await visible(), false);
  await js('customerView.__saved=true;void 0');
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS editing also clears customer only after Save; reopening retains cleared state; no renderer errors');
  clearTimeout(timeout);
  app.exit(0);
}).catch(error => { console.error(error.stack || error); app.exit(1); });
